#!/usr/bin/env python3
"""Generate the seven unrolled BLAKE3 rounds. Uses Python stdlib and forge fmt."""
from pathlib import Path
import argparse
import os
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
MASK = sum(0xFFFFFFFF << (64 * i) for i in range(4))
IV = [0x6A09E667, 0xBB67AE85, 0x3C6EF372, 0xA54FF53A,
      0x510E527F, 0x9B05688C, 0x1F83D9AB, 0x5BE0CD19]
PERM = [2, 6, 3, 10, 7, 0, 4, 13, 1, 11, 12, 5, 9, 14, 15, 8]

def packed(words):
    return hex(sum(w << (64 * i) for i, w in enumerate(words)))

def lanes(indices):
    groups = {}
    for j, i in enumerate(indices):
        key = (i // 8, j * 64 - (i % 8) * 32)
        groups[key] = groups.get(key, 0) | (0xffffffff << (64 * j))
    terms = []
    for (source, shift), mask in groups.items():
        term = f"m{source}"
        if shift:
            term = f"{'shl' if shift > 0 else 'shr'}({abs(shift)}, {term})"
        terms.append(f"and({term}, {hex(mask)})")
    while len(terms) > 1:
        terms = [f"or({terms[0]}, {terms[1]})"] + terms[2:]
    return terms[0]

overloads = "\n\n".join(f"""    /// @notice Hash the {n * 32} bytes of the array's big-endian words.
    function hash(uint256[{n}] memory values) internal pure returns (uint256) {{
        uint256 p;
        assembly (\"memory-safe\") {{ p := values }}
        return _hash(p, {n * 32});
    }}""" for n in range(1, 9))

def mix(x, y):
    return f"                a, b, c, d := g(a, b, c, d, {x}, {y})"

def mix_body():
    return f"""                {{
                    let mask := {hex(MASK)}
                    a := and(add(add(a, b), x), mask)
                    d := xor(d, a)
                    d := and(shr(16, mul(d, 0x100000001)), mask)
                    c := and(add(c, d), mask)
                    b := xor(b, c)
                    b := and(shr(12, mul(b, 0x100000001)), mask)
                    a := and(add(add(a, b), y), mask)
                    d := xor(d, a)
                    d := and(shr(8, mul(d, 0x100000001)), mask)
                    c := and(add(c, d), mask)
                    b := xor(b, c)
                    b := and(shr(7, mul(b, 0x100000001)), mask)
                }}"""
rounds = []
m = list(range(16))
for i in range(7):
    rounds.append(f"""                // Round {i + 1}: four columns, then four diagonals.
{mix(lanes(m[0:8:2]), lanes(m[1:8:2]))}
                b := or(shr(64, b), shl(192, b))
                c := or(shr(128, c), shl(128, c))
                d := or(shr(192, d), shl(64, d))
{mix(lanes(m[8:16:2]), lanes(m[9:16:2]))}
                b := or(shr(192, b), shl(64, b))
                c := or(shr(128, c), shl(128, c))
                d := or(shr(64, d), shl(192, d))""")
    m = [m[i] for i in PERM]

source = f'''// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

/// @title BLAKE3Lib
/// @notice Unkeyed BLAKE3-256 of raw bytes or concatenated big-endian uint256 words.
/// @dev Generated by scripts/generate.py. Each SIMD register has four u32 lanes
///      at bit offsets 0, 64, 128, 192; the upper half of each lane absorbs carry.
///      Supports empty arrays and the full BLAKE3 chunk tree for dynamic arrays.
library BLAKE3Lib {{
{overloads}

    /// @notice Hash all words; an empty array produces the standard empty digest.
    function hash(uint256[] memory values) internal pure returns (uint256) {{
        uint256 p;
        assembly ("memory-safe") {{ p := add(values, 32) }}
        return _hash(p, values.length << 5);
    }}

    /// @notice Hash exactly the bytes of data, with no length prefix or padding.
    function hash(bytes memory data) internal pure returns (uint256) {{
        uint256 p;
        assembly ("memory-safe") {{ p := add(data, 32) }}
        return _hash(p, data.length);
    }}

    function _hash(uint256 p, uint256 n) private pure returns (uint256 result) {{
        assembly ("memory-safe") {{
            function reverseBytes(x) -> y {{
                x := or(shl(8, and(x, 0x00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff)), and(shr(8, x), 0x00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff))
                x := or(shl(16, and(x, 0x0000ffff0000ffff0000ffff0000ffff0000ffff0000ffff0000ffff0000ffff)), and(shr(16, x), 0x0000ffff0000ffff0000ffff0000ffff0000ffff0000ffff0000ffff0000ffff))
                x := or(shl(32, and(x, {hex(MASK)})), and(shr(32, x), {hex(MASK)}))
                x := or(shl(64, and(x, 0x0000000000000000ffffffffffffffff0000000000000000ffffffffffffffff)), and(shr(64, x), 0x0000000000000000ffffffffffffffff0000000000000000ffffffffffffffff))
                y := or(shl(128, x), shr(128, x))
            }}
            function compact(x) -> y {{
                x := and(or(x, shr(32, x)), 0x0000000000000000ffffffffffffffff0000000000000000ffffffffffffffff)
                y := and(or(x, shr(64, x)), 0xffffffffffffffffffffffffffffffff)
            }}
            function loadBlock(p0, size, s) {{
                let lo := 0
                let hi := 0
                if size {{
                    lo := reverseBytes(mload(p0))
                    // Bytes past the logical end can contain arbitrary data.
                    if lt(size, 32) {{ lo := and(lo, sub(shl(shl(3, size), 1), 1)) }}
                }}
                if gt(size, 32) {{
                    hi := reverseBytes(mload(add(p0, 32)))
                    if lt(size, 64) {{ hi := and(hi, sub(shl(shl(3, sub(size, 32)), 1), 1)) }}
                }}
                mstore(s, lo)
                mstore(add(s, 32), hi)
            }}
            // Multiplication by 2**32+1 duplicates each u32 into its padding;
            // shifting and masking then rotates all four lanes in parallel.
            function g(a, b, c, d, x, y) -> aa, bb, cc, dd {{
{mix_body()}
                aa := a
                bb := b
                cc := c
                dd := d
            }}
            function compress(s) -> oa, ob {{
                let a := mload(add(s, 64))
                let b := mload(add(s, 96))
                let c := {packed(IV[:4])}
                let d := mload(add(s, 128))
                let m0 := mload(s)
                let m1 := mload(add(s, 32))
{chr(10).join(rounds)}
                oa := xor(a, c)
                ob := xor(b, d)
            }}
            function chunk(p0, size, counter, s, root) -> a, b {{
                a := {packed(IV[:4])}
                b := {packed(IV[4:])}
                let flags := 1 // CHUNK_START
                for {{ }} 1 {{ }} {{
                    let take := 64
                    if lt(size, 64) {{ take := size }}
                    let f := flags
                    if iszero(gt(size, 64)) {{ f := or(f, or(2, root)) }} // CHUNK_END
                    loadBlock(p0, take, s)
                    mstore(add(s, 64), a)
                    mstore(add(s, 96), b)
                    mstore(add(s, 128), or(and(counter, 0xffffffff), or(shl(64, shr(32, counter)), or(shl(128, take), shl(192, f)))))
                    a, b := compress(s)
                    if iszero(gt(size, 64)) {{ break }}
                    p0 := add(p0, 64)
                    size := sub(size, 64)
                    flags := 0
                }}
            }}
            function parent(leftA, leftB, rightA, rightB, s, root) -> a, b {{
                mstore(s, or(compact(leftA), shl(128, compact(leftB))))
                mstore(add(s, 32), or(compact(rightA), shl(128, compact(rightB))))
                mstore(add(s, 64), {packed(IV[:4])})
                mstore(add(s, 96), {packed(IV[4:])})
                mstore(add(s, 128), or(shl(128, 64), shl(192, or(4, root))))
                a, b := compress(s)
            }}
            // Temporary storage starts above Solidity's allocations. The first
            // 160 bytes hold the compression input; each tree CV takes 64 bytes.
            let s := mload(0x40)
            let base := add(s, 160)
            let top := base
            let counter := 0
            for {{ }} gt(n, 1024) {{ }} {{
                let a, b := chunk(p, 1024, counter, s, 0)
                counter := add(counter, 1)
                let total := counter
                for {{ }} iszero(and(total, 1)) {{ total := shr(1, total) }} {{
                    top := sub(top, 64)
                    a, b := parent(mload(top), mload(add(top, 32)), a, b, s, 0)
                }}
                mstore(top, a)
                mstore(add(top, 32), b)
                top := add(top, 64)
                p := add(p, 1024)
                n := sub(n, 1024)
            }}
            let a, b := chunk(p, n, counter, s, mul(eq(top, base), 8))
            for {{ }} gt(top, base) {{ }} {{
                top := sub(top, 64)
                a, b := parent(mload(top), mload(add(top, 32)), a, b, s, mul(eq(top, base), 8))
            }}
            // Serialize eight little-endian u32 output words to a big-endian uint256.
            result := reverseBytes(or(compact(a), shl(128, compact(b))))
        }}
    }}
}}
'''
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
forge = shutil.which("forge") or os.path.expanduser("~/.foundry/bin/forge")
source = subprocess.run([forge, "fmt", "--raw", "-"], input=source,
                        text=True, capture_output=True, check=True, cwd=ROOT).stdout
destination = ROOT / "src/BLAKE3Lib.sol"
if args.check:
    assert destination.read_text() == source, "Run python3 scripts/generate.py"
else:
    destination.write_text(source)
