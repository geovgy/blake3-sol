#!/usr/bin/env python3
"""Generate the seven unrolled BLAKE3 rounds. Uses Python stdlib and forge fmt."""
from pathlib import Path
import argparse
import os
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
MASK = sum(0xFFFFFFFF << (64 * i) for i in range(4))
IV = [0x6A09E667, 0xBB67AE85, 0x3C6EF372, 0xA54FF53A,
      0x510E527F, 0x9B05688C, 0x1F83D9AB, 0x5BE0CD19]
PERM = [2, 6, 3, 10, 7, 0, 4, 13, 1, 11, 12, 5, 9, 14, 15, 8]

def packed(words):
    # Lane zero occupies bits 192..223. Reversing the lane order avoids
    # reversing the u32 word order when loading or serializing message words.
    return hex(sum(w << (64 * i) for i, w in enumerate(reversed(words))))

def lanes(indices):
    # m0/m1 retain their original u32 word order; only bytes within each u32
    # have been swapped. Gather each word into its reversed SIMD lane.
    groups = {}
    for j, i in enumerate(indices):
        key = (i // 8, (3 - j) * 64 - (7 - i % 8) * 32)
        groups[key] = groups.get(key, 0) | (0xffffffff << (64 * (3 - j)))
    terms = []
    for (source, shift), mask in groups.items():
        term = f"m{source}"
        if shift:
            term = f"{'shl' if shift > 0 else 'shr'}({abs(shift)}, {term})"
        terms.append(f"and({term}, {hex(mask)})")
    while len(terms) > 1:
        terms = [f"or({terms[0]}, {terms[1]})"] + terms[2:]
    return terms[0]

overloads = "\n\n".join(f"""    /// @notice Hash the {n * 32} bytes of the array's big-endian words.
    function hash(uint256[{n}] memory values) internal pure returns (uint256) {{
        uint256 p;
        assembly (\"memory-safe\") {{ p := values }}
        return _hash(p, {n * 32});
    }}""" for n in range(1, 9))

def mix(x, y):
    # Reverse both tuples to reduce the EVM backend's stack shuffling.
    return f"                d, c, b, a := g(d, c, b, a, {y}, {x})"

def mix_body():
    return f"""                {{
                    let mask := {hex(MASK)}
                    a := and(add(add(a, b), x), mask)
                    d := xor(d, a)
                    d := and(shr(16, mul(d, 0x100000001)), mask)
                    c := and(add(c, d), mask)
                    b := xor(b, c)
                    b := and(shr(12, mul(b, 0x100000001)), mask)
                    a := and(add(add(a, b), y), mask)
                    d := xor(d, a)
                    d := and(shr(8, mul(d, 0x100000001)), mask)
                    c := and(add(c, d), mask)
                    b := xor(b, c)
                    b := and(shr(7, mul(b, 0x100000001)), mask)
                }}"""
rounds = []
m = list(range(16))
for i in range(7):
    rounds.append(f"""                // Round {i + 1}: four columns, then four diagonals.
{mix(lanes(m[0:8:2]), lanes(m[1:8:2]))}
                b := or(shr(192, b), shl(64, b))
                c := or(shr(128, c), shl(128, c))
                d := or(shr(64, d), shl(192, d))
{mix(lanes(m[8:16:2]), lanes(m[9:16:2]))}
                b := or(shr(64, b), shl(192, b))
                c := or(shr(128, c), shl(128, c))
                d := or(shr(192, d), shl(64, d))""")
    m = [m[i] for i in PERM]

source = f'''// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

/// @title BLAKE3Lib
/// @notice Unkeyed BLAKE3-256 of raw bytes or concatenated big-endian uint256 words.
/// @dev Generated by scripts/generate.py. Each SIMD register has four u32 lanes
///      at bit offsets 192, 128, 64, 0; the upper half of each lane absorbs carry.
///      Supports empty arrays and the full BLAKE3 chunk tree for dynamic arrays.
library BLAKE3Lib {{
{overloads}

    /// @notice Hash all words; an empty array produces the standard empty digest.
    function hash(uint256[] memory values) internal pure returns (uint256) {{
        uint256 p;
        assembly ("memory-safe") {{ p := add(values, 32) }}
        return _hash(p, values.length << 5);
    }}

    /// @notice Hash exactly the bytes of data, with no length prefix or padding.
    function hash(bytes memory data) internal pure returns (uint256) {{
        uint256 p;
        assembly ("memory-safe") {{ p := add(data, 32) }}
        return _hash(p, data.length);
    }}

    function _hash(uint256 p, uint256 n) private pure returns (uint256 result) {{
        if (n == 0) return 0xaf1349b9f5f9a1a6a0404dea36dcc9499bcb25c9adc112b7cc9a93cae41f3262;
        assembly ("memory-safe") {{
            // Swap bytes inside each u32, preserving the message word order.
            function wordEndian(x) -> y {{
                x := or(shl(8, and(x, 0x00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff)), and(shr(8, x), 0x00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff00ff))
                y := or(shl(16, and(x, 0x0000ffff0000ffff0000ffff0000ffff0000ffff0000ffff0000ffff0000ffff)), and(shr(16, x), 0x0000ffff0000ffff0000ffff0000ffff0000ffff0000ffff0000ffff0000ffff))
            }}
            function compact(x) -> y {{
                x := and(or(x, shr(32, x)), 0x0000000000000000ffffffffffffffff0000000000000000ffffffffffffffff)
                y := and(or(x, shr(64, x)), 0xffffffffffffffffffffffffffffffff)
            }}
            function loadBlock(p0, size) -> lo, hi {{
                if size {{
                    lo := mload(p0)
                    // Bytes past the logical end can contain arbitrary data.
                    if lt(size, 32) {{ lo := and(lo, not(shr(shl(3, size), not(0)))) }}
                    lo := wordEndian(lo)
                }}
                if gt(size, 32) {{
                    hi := mload(add(p0, 32))
                    if lt(size, 64) {{ hi := and(hi, not(shr(shl(3, sub(size, 32)), not(0)))) }}
                    hi := wordEndian(hi)
                }}
            }}
            // Multiplication by 2**32+1 duplicates each u32 into its padding;
            // shifting and masking then rotates all four lanes in parallel.
            function g(d, c, b, a, y, x) -> dd, cc, bb, aa {{
{mix_body()}
                aa := a
                bb := b
                cc := c
                dd := d
            }}
            function compress(m0, m1, a, b, d) -> oa, ob {{
                let c := {packed(IV[:4])}
{chr(10).join(rounds)}
                oa := xor(a, c)
                ob := xor(b, d)
            }}
            function chunk(p0, size, counter, root) -> a, b {{
                a := {packed(IV[:4])}
                b := {packed(IV[4:])}
                let flags := 1 // CHUNK_START
                counter := or(shl(192, and(counter, 0xffffffff)), shl(128, shr(32, counter)))
                // Leave the final block for CHUNK_END, including full blocks
                // at exact multiples of 64. A chunk never exceeds 1024 bytes.
                for {{ }} gt(size, 64) {{ }} {{
                    let m0, m1 := loadBlock(p0, 64)
                    a, b := compress(m0, m1, a, b, or(counter, or(shl(64, 64), flags)))
                    p0 := add(p0, 64)
                    size := sub(size, 64)
                    flags := 0
                }}
                let m0, m1 := loadBlock(p0, size)
                a, b := compress(m0, m1, a, b, or(counter, or(shl(64, size), or(flags, or(2, root)))))
            }}
            function parent(leftA, leftB, rightA, rightB, root) -> a, b {{
                a, b := compress(or(shl(128, compact(leftA)), compact(leftB)), or(shl(128, compact(rightA)), compact(rightB)), {packed(IV[:4])}, {packed(IV[4:])}, or(shl(64, 64), or(4, root)))
            }}
            switch gt(n, 128)
            case 0 {{
                // One chunk with counter zero: no CV stack or chunk loop.
                let a := {packed(IV[:4])}
                let b := {packed(IV[4:])}
                let flags := 11 // CHUNK_START | CHUNK_END | ROOT
                if gt(n, 64) {{
                    let m0, m1 := loadBlock(p, 64)
                    a, b := compress(m0, m1, a, b, or(shl(64, 64), 1))
                    p := add(p, 64)
                    n := sub(n, 64)
                    flags := 10 // CHUNK_END | ROOT
                }}
                let m0, m1 := loadBlock(p, n)
                a, b := compress(m0, m1, a, b, or(shl(64, n), flags))
                result := wordEndian(or(shl(128, compact(a)), compact(b)))
            }}
            default {{
                // Temporary storage starts above Solidity's allocations. Each
                // tree CV takes 64 bytes.
                let base := mload(0x40)
                let top := base
                let counter := 0
                for {{ }} gt(n, 1024) {{ }} {{
                    let a, b := chunk(p, 1024, counter, 0)
                    counter := add(counter, 1)
                    let total := counter
                    for {{ }} iszero(and(total, 1)) {{ total := shr(1, total) }} {{
                        top := sub(top, 64)
                        a, b := parent(mload(top), mload(add(top, 32)), a, b, 0)
                    }}
                    mstore(top, a)
                    mstore(add(top, 32), b)
                    top := add(top, 64)
                    p := add(p, 1024)
                    n := sub(n, 1024)
                }}
                let a, b := chunk(p, n, counter, mul(eq(top, base), 8))
                for {{ }} gt(top, base) {{ }} {{
                    top := sub(top, 64)
                    a, b := parent(mload(top), mload(add(top, 32)), a, b, mul(eq(top, base), 8))
                }}
                // Serialize eight little-endian u32 output words to a big-endian uint256.
                result := wordEndian(or(shl(128, compact(a)), compact(b)))
            }}
        }}
    }}
}}
'''
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
forge = shutil.which("forge") or os.path.expanduser("~/.foundry/bin/forge")
source = subprocess.run([forge, "fmt", "--raw", "-"], input=source,
                        text=True, capture_output=True, check=True, cwd=ROOT).stdout
destination = ROOT / "src/BLAKE3Lib.sol"
if args.check:
    assert destination.read_text() == source, "Run python3 scripts/generate.py"
else:
    destination.write_text(source)
